"""
models/user.py
===============
User model — no password, no JWT, no login.
Only purpose: give a stable identity to RAG memories.

UUID is generated by the frontend (localStorage) on first visit.
Backend creates/confirms the user on first RAG call.

Future-proof: when you add real auth, replace anonymous UUID with
authenticated user.id — no memory schema changes needed.
"""

import uuid
from sqlalchemy import Column, String, Boolean, DateTime, Enum
from sqlalchemy.orm import relationship
from sqlalchemy.sql import func
from db.DB import Base
import enum


class UserRole(str, enum.Enum):
    ADMIN    = "admin"
    TRAINER  = "trainer"
    STUDENT  = "student"
    VIEWER   = "viewer"


class User(Base):
    __tablename__ = "users"

    id = Column(String(36), primary_key=True, index=True)
    display_name = Column(String(100), nullable=False, default="Administrator")
    role = Column(String(20), nullable=False, default="admin")
    is_active = Column(Boolean, default=True)
    created_at = Column(DateTime, server_default=func.now())
    last_seen_at = Column(DateTime, nullable=True)