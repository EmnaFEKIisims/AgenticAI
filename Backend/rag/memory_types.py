"""
rag/memory_types.py
====================
Defines the 6 memory types stored in ChromaDB.
Every memory document has a type, user_id, content, and metadata.

Design principle:
  - Content    = what the LLM reads (natural language)
  - Metadata   = what we filter on (user_id, type, planning_id, timestamp)
  - Embedding  = vector representation of Content (auto-generated by ChromaDB)
"""

from enum import Enum
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Optional
import uuid


class MemoryType(str, Enum):
    """The 6 types of memory the RAG system stores."""

    # A — Soft preferences extracted from user behavior
    USER_PREFERENCE      = "user_preference"

    # B — Why a decision was made by an agent
    DECISION_HISTORY     = "decision_history"

    # C — Generated / rejected / modified plannings
    PLANNING_HISTORY     = "planning_history"

    # D — Detected conflicts and how they were resolved
    CONFLICT_CORRECTION  = "conflict_correction"

    # E — Explicit user feedback on a planning
    USER_FEEDBACK        = "user_feedback"

    # F — Pedagogical rules and heuristics
    PEDAGOGICAL_KNOWLEDGE = "pedagogical_knowledge"


@dataclass
class MemoryDocument:
    """
    One document stored in ChromaDB.

    content   → the natural language text (embedded + returned to LLM)
    metadata  → structured filters (never embedded)
    doc_id    → unique ChromaDB document ID
    """
    content:     str
    memory_type: MemoryType
    user_id:     str                          # session UUID from frontend

    # Optional enrichment
    planning_id:  Optional[str] = None        # links to a specific planning batch
    tags:         list[str]     = field(default_factory=list)
    importance:   int           = 1           # 1=low 2=medium 3=high

    # Auto-generated
    doc_id:       str = field(default_factory=lambda: str(uuid.uuid4()))
    created_at:   str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    def to_metadata(self) -> dict:
        """Returns the metadata dict stored alongside the ChromaDB vector."""
        return {
            "memory_type": self.memory_type.value,
            "user_id":     self.user_id,
            "planning_id": self.planning_id or "",
            "tags":        ",".join(self.tags),
            "importance":  self.importance,
            "created_at":  self.created_at,
        }

    @classmethod
    def from_chroma(cls, doc_id: str, content: str, metadata: dict) -> "MemoryDocument":
        """Reconstructs a MemoryDocument from ChromaDB query results."""
        return cls(
            doc_id       = doc_id,
            content      = content,
            memory_type  = MemoryType(metadata.get("memory_type", "user_preference")),
            user_id      = metadata.get("user_id", ""),
            planning_id  = metadata.get("planning_id") or None,
            tags         = metadata.get("tags", "").split(",") if metadata.get("tags") else [],
            importance   = int(metadata.get("importance", 1)),
            created_at   = metadata.get("created_at", ""),
        )


# =============================================================================
#  CONTENT TEMPLATES — how memories are verbalized for the LLM
# =============================================================================

def format_user_preference(preference: str, source: str = "") -> str:
    src = f" (observed from: {source})" if source else ""
    return f"User preference{src}: {preference}"


def format_decision_history(decision: str, reason: str, outcome: str = "") -> str:
    parts = [f"Past decision: {decision}", f"Reason: {reason}"]
    if outcome:
        parts.append(f"Outcome: {outcome}")
    return ". ".join(parts)


def format_planning_history(action: str, summary: str, constraints_summary: str = "") -> str:
    parts = [f"Planning {action}: {summary}"]
    if constraints_summary:
        parts.append(f"Constraints: {constraints_summary}")
    return ". ".join(parts)


def format_conflict(conflict: str, resolution: str, affected: str = "") -> str:
    parts = [f"Conflict detected: {conflict}", f"Resolution: {resolution}"]
    if affected:
        parts.append(f"Affected: {affected}")
    return ". ".join(parts)


def format_feedback(feedback: str, context: str = "") -> str:
    ctx = f" (context: {context})" if context else ""
    return f"User feedback{ctx}: {feedback}"


def format_pedagogical(rule: str, source: str = "ISO 21001") -> str:
    return f"Pedagogical rule ({source}): {rule}"